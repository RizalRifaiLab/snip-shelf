//! Background helpers: watch the clipboard, watch the screenshot folder, make thumbnails,
//! run the snip/record tools and put items back on the clipboard.

use crate::mac;
use crate::model::{self, Kind};
use eframe::egui;
use std::collections::{HashMap, HashSet};
use std::hash::{Hash, Hasher};
use std::path::{Path, PathBuf};
use std::sync::atomic::{AtomicIsize, Ordering};
use std::sync::mpsc::Sender;
use std::sync::Arc;
use std::time::{Duration, SystemTime};

pub enum Incoming {
    Text(String),
    Image { path: PathBuf, width: u32, height: u32, hash: u64, source: String },
    FileRef { path: PathBuf, kind: Kind, source: String, auto_copy: bool },
    Thumb { id: u64, image: egui::ColorImage },
    ThumbFailed { id: u64 },
    Toast(String),
    /// A choice from the menu-bar icon.
    Menu(String),
}

/// The pasteboard change count we wrote ourselves, so the watcher skips it.
pub type IgnoreCount = Arc<AtomicIsize>;

fn hash_bytes(b: &[u8]) -> u64 {
    let mut h = std::collections::hash_map::DefaultHasher::new();
    b.hash(&mut h);
    h.finish()
}

pub fn text_hash(s: &str) -> u64 {
    hash_bytes(s.as_bytes())
}

fn stamp() -> String {
    let secs = model::now_secs();
    let ms = SystemTime::now()
        .duration_since(SystemTime::UNIX_EPOCH)
        .map(|d| d.subsec_millis())
        .unwrap_or(0);
    format!("{secs}-{ms:03}")
}

/// Save raw RGBA pixels as a PNG in the captures folder.
fn save_rgba_png(w: u32, h: u32, rgba: &[u8], prefix: &str) -> Option<PathBuf> {
    let path = model::captures_dir().join(format!("{prefix} {}.png", stamp()));
    let img = image::RgbaImage::from_raw(w, h, rgba.to_vec())?;
    img.save(&path).ok()?;
    Some(path)
}

pub fn start_clipboard_watcher(tx: Sender<Incoming>, ctx: egui::Context, ignore: IgnoreCount) {
    std::thread::spawn(move || {
        let mut clip = match arboard::Clipboard::new() {
            Ok(c) => c,
            Err(_) => return,
        };
        let mut last = mac::change_count();
        loop {
            std::thread::sleep(Duration::from_millis(450));
            let count = mac::change_count();
            if count == last {
                continue;
            }
            last = count;
            if count == ignore.load(Ordering::SeqCst) {
                continue;
            }
            let types = mac::types();
            // Password managers mark secrets as concealed/transient: never keep those.
            if types.iter().any(|t| {
                t.contains("ConcealedType") || t.contains("TransientType") || t.contains("AutoGeneratedType")
            }) {
                continue;
            }
            let has_file = types.iter().any(|t| t == "public.file-url");
            let has_image = types
                .iter()
                .any(|t| t == "public.png" || t == "public.tiff" || t == "public.jpeg");

            let msg = if has_file {
                mac::copied_file().map(|p| {
                    let kind = model::ext_kind(&p);
                    Incoming::FileRef { path: p, kind, source: "Copied file".into(), auto_copy: false }
                })
            } else if has_image {
                match clip.get_image() {
                    Ok(img) => {
                        let hash = hash_bytes(&img.bytes);
                        save_rgba_png(img.width as u32, img.height as u32, &img.bytes, "Copied").map(|path| {
                            Incoming::Image {
                                path,
                                width: img.width as u32,
                                height: img.height as u32,
                                hash,
                                source: "Copied picture".into(),
                            }
                        })
                    }
                    Err(_) => None,
                }
            } else {
                match clip.get_text() {
                    Ok(t) if !t.trim().is_empty() => Some(Incoming::Text(t)),
                    _ => None,
                }
            };
            if let Some(m) = msg {
                let _ = tx.send(m);
                ctx.request_repaint();
            }
        }
    });
}

/// Where macOS saves screenshots and recordings (Desktop unless changed in the Screenshot app).
pub fn screenshot_folder() -> PathBuf {
    let home = dirs::home_dir().unwrap_or_else(|| PathBuf::from("/"));
    if let Ok(out) = std::process::Command::new("defaults")
        .args(["read", "com.apple.screencapture", "location"])
        .output()
    {
        if out.status.success() {
            let s = String::from_utf8_lossy(&out.stdout).trim().to_string();
            if !s.is_empty() {
                let p = if let Some(rest) = s.strip_prefix("~/") {
                    home.join(rest)
                } else {
                    PathBuf::from(s)
                };
                if p.is_dir() {
                    return p;
                }
            }
        }
    }
    dirs::desktop_dir().unwrap_or_else(|| home.join("Desktop"))
}

fn has_capture_flag(path: &Path) -> bool {
    #[cfg(target_os = "macos")]
    {
        use std::ffi::CString;
        use std::os::unix::ffi::OsStrExt;
        let Ok(p) = CString::new(path.as_os_str().as_bytes()) else { return false };
        let name = CString::new("com.apple.metadata:kMDItemIsScreenCapture").unwrap();
        let r = unsafe { libc::getxattr(p.as_ptr(), name.as_ptr(), std::ptr::null_mut(), 0, 0, 0) };
        r >= 0
    }
    #[cfg(not(target_os = "macos"))]
    {
        let _ = path;
        false
    }
}

fn looks_like_capture(path: &Path) -> bool {
    const PREFIXES: &[&str] = &[
        "screenshot",
        "screen shot",
        "screen recording",
        "cuplikan layar",
        "rekaman layar",
        "bildschirmfoto",
        "bildschirmaufnahme",
        "capture d",
        "enregistrement de l",
        "captura de pantalla",
        "grabación de pantalla",
        "istantanea",
        "registrazione schermo",
    ];
    let name = path
        .file_name()
        .map(|n| n.to_string_lossy().to_lowercase())
        .unwrap_or_default();
    if name.starts_with('.') {
        return false;
    }
    PREFIXES.iter().any(|p| name.starts_with(p)) || has_capture_flag(path)
}

pub fn start_folder_watcher(tx: Sender<Incoming>, ctx: egui::Context, auto_copy: Arc<std::sync::atomic::AtomicBool>) {
    std::thread::spawn(move || {
        let folder = screenshot_folder();
        let mut seen: HashSet<PathBuf> = HashSet::new();
        if let Ok(rd) = std::fs::read_dir(&folder) {
            for e in rd.flatten() {
                seen.insert(e.path());
            }
        }
        let mut pending: HashMap<PathBuf, u64> = HashMap::new();
        loop {
            std::thread::sleep(Duration::from_millis(1200));
            let Ok(rd) = std::fs::read_dir(&folder) else { continue };
            for e in rd.flatten() {
                let p = e.path();
                if seen.contains(&p) {
                    continue;
                }
                let kind = model::ext_kind(&p);
                if kind == Kind::File || !looks_like_capture(&p) {
                    // Not a capture; check again later only if it might still get its flag.
                    if kind == Kind::File {
                        seen.insert(p);
                    }
                    continue;
                }
                let size = e.metadata().map(|m| m.len()).unwrap_or(0);
                // Wait until the file stops growing (recordings are written for a while).
                match pending.get(&p) {
                    Some(prev) if *prev == size && size > 0 => {
                        pending.remove(&p);
                        seen.insert(p.clone());
                        let auto = auto_copy.load(Ordering::SeqCst);
                        let msg = if kind == Kind::Image {
                            Incoming::FileRef { path: p, kind, source: "Screenshot".into(), auto_copy: auto }
                        } else {
                            Incoming::FileRef { path: p, kind, source: "Recording".into(), auto_copy: auto }
                        };
                        let _ = tx.send(msg);
                        ctx.request_repaint();
                    }
                    _ => {
                        pending.insert(p, size);
                    }
                }
            }
        }
    });
}

/// Make a small picture for a card (pictures are shrunk, videos use Quick Look).
pub fn start_thumbnail(tx: Sender<Incoming>, ctx: egui::Context, id: u64, path: PathBuf, kind: Kind) {
    std::thread::spawn(move || {
        let src = if kind == Kind::Video {
            let out = model::thumbs_dir();
            let _ = std::process::Command::new("qlmanage")
                .args(["-t", "-s", "480", "-o"])
                .arg(&out)
                .arg(&path)
                .stdout(std::process::Stdio::null())
                .stderr(std::process::Stdio::null())
                .status();
            let name = format!("{}.png", path.file_name().map(|n| n.to_string_lossy().to_string()).unwrap_or_default());
            out.join(name)
        } else {
            path.clone()
        };
        let msg = match image::open(&src) {
            Ok(img) => {
                let t = img.thumbnail(520, 360).to_rgba8();
                let size = [t.width() as usize, t.height() as usize];
                Incoming::Thumb { id, image: egui::ColorImage::from_rgba_unmultiplied(size, t.as_raw()) }
            }
            Err(_) => Incoming::ThumbFailed { id },
        };
        let _ = tx.send(msg);
        ctx.request_repaint();
    });
}

/// Put an item back on the clipboard.
pub fn copy_item(item: model::Item, tx: Sender<Incoming>, ctx: egui::Context, ignore: IgnoreCount) {
    std::thread::spawn(move || {
        let ok = match item.kind {
            Kind::Text => {
                let t = item.text.clone().unwrap_or_default();
                arboard::Clipboard::new().and_then(|mut c| c.set_text(t)).is_ok()
            }
            Kind::Image => match item.path.as_ref().and_then(|p| image::open(p).ok()) {
                Some(img) => {
                    let rgba = img.to_rgba8();
                    let data = arboard::ImageData {
                        width: rgba.width() as usize,
                        height: rgba.height() as usize,
                        bytes: std::borrow::Cow::Owned(rgba.into_raw()),
                    };
                    arboard::Clipboard::new().and_then(|mut c| c.set_image(data)).is_ok()
                }
                None => false,
            },
            Kind::Video | Kind::File => item.path.as_ref().map(|p| p.exists() && mac::set_file(p)).unwrap_or(false),
        };
        ignore.store(mac::change_count(), Ordering::SeqCst);
        let what = match item.kind {
            Kind::Text => "Text",
            Kind::Image => "Picture",
            Kind::Video => "Recording",
            Kind::File => "File",
        };
        let msg = if ok {
            format!("{what} copied — press ⌘V to paste")
        } else {
            format!("Couldn't copy this {} (is the file still there?)", what.to_lowercase())
        };
        let _ = tx.send(Incoming::Toast(msg));
        ctx.request_repaint();
    });
}

/// Run the macOS capture tool. `video` records the screen; otherwise snip an area.
pub fn run_capture(video: bool, tx: Sender<Incoming>, ctx: egui::Context) {
    std::thread::spawn(move || {
        let dir = model::captures_dir();
        let (path, args): (PathBuf, Vec<&str>) = if video {
            (dir.join(format!("Recording {}.mov", stamp())), vec!["-i", "-v", "-U", "-Jvideo", "-k"])
        } else {
            (dir.join(format!("Snip {}.png", stamp())), vec!["-i", "-x"])
        };
        let status = std::process::Command::new("screencapture").args(&args).arg(&path).status();
        let exists = path.exists() && std::fs::metadata(&path).map(|m| m.len() > 0).unwrap_or(false);
        let msg = match (status, exists) {
            (_, true) => {
                let kind = if video { Kind::Video } else { Kind::Image };
                Incoming::FileRef {
                    path,
                    kind,
                    source: if video { "Recording".into() } else { "Snip".into() },
                    auto_copy: true,
                }
            }
            (Err(_), _) => Incoming::Toast("The macOS capture tool couldn't start".into()),
            _ => Incoming::Toast(if video { "Recording cancelled".into() } else { "Snip cancelled".into() }),
        };
        let _ = tx.send(msg);
        ctx.request_repaint();
    });
}
